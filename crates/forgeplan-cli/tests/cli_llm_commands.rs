// ── decompose ───────────────────────────────────────────────────────────────

/// `forgeplan decompose` reads a PRD and asks the LLM for a task plan.
/// The mock returns a numbered plan; the command must print it verbatim.
#[test]
fn decompose_prints_llm_plan() {
    let tmp = TempDir::new().unwrap();
    init_workspace(&tmp);
    let prd = new_artifact(&tmp, "prd", "Decompose me");

    let plan = "1. RFC-A — foundation\n2. RFC-B — integration\n3. RFC-C — polish";
    let server = MockLlmServer::start(vec![plan.into()]);
    configure_llm(&tmp, &server.base_url(), "mock-model", "mock-key");

    let out = forgeplan()
        .args(["decompose", &prd])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "decompose failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.contains("RFC-A") && stdout.contains("RFC-B") && stdout.contains("RFC-C"),
        "decompose must print the LLM plan; got:\n{stdout}"
    );
    assert!(
        stdout.contains("Next:") || stdout.contains("forgeplan new rfc"),
        "decompose must emit the create-RFC hint; got:\n{stdout}"
    );
    assert_eq!(server.requests(), 1);
    server.stop();
}

