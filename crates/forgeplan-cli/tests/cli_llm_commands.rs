// ── route ───────────────────────────────────────────────────────────────────

/// `forgeplan route` classifies a task string and recommends a pipeline.
/// It does NOT call the LLM — it's a heuristic — but it must print a route.
#[test]
fn route_classifies_and_recommends() {
    let tmp = TempDir::new().unwrap();
    init_workspace(&tmp);

    for (input, must_contain) in [
        ("fix typo in readme", "tactical"),
        ("add user authentication", "standard"),
        ("migrate database schema", "deep"),
        ("security audit of auth flow", "critical"),
    ] {
        let out = forgeplan()
            .args(["route", input])
            .current_dir(tmp.path())
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "route '{input}' failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        let stdout = String::from_utf8_lossy(&out.stdout).to_lowercase();
        assert!(
            stdout.contains(must_contain) || stdout.contains("prd") || stdout.contains("pipeline"),
            "route '{input}' must mention {must_contain} or a pipeline; got:\n{stdout}"
        );
    }
}

// ── LLM failure path ───────────────────────────────────────────────────────

/// When the LLM server is unreachable (mock stopped), commands must fail
/// with a clean error — not panic or hang.
#[test]
fn generate_fails_cleanly_when_llm_unreachable() {
    let tmp = TempDir::new().unwrap();
    init_workspace(&tmp);

    // Configure a URL that is NOT listening.
    let dead_url = "http://127.0.0.1:1/v1";
    configure_llm(&tmp, dead_url, "mock-model", "mock-key");

    let out = forgeplan()
        .args(["generate", "prd", "unreachable"])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    assert!(
        !out.status.success(),
        "generate must fail on unreachable LLM"
    );
    let combined = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        combined.contains("LLM call failed") || combined.contains("Fix:"),
        "expected a clean LLM failure; got:\n{combined}"
    );
}
