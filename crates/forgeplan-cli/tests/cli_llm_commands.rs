/// `reason --json` must emit parseable JSON.
#[test]
fn reason_json_flag_outputs_parseable() {
    let tmp = TempDir::new().unwrap();
    init_workspace(&tmp);
    let adr = new_artifact(&tmp, "adr", "JSON reason");

    let adi_json = serde_json::json!({
        "hypotheses": [],
        "deductions": [],
        "evidence_needed": [],
        "recommendation": "json-out",
        "confidence": "Low",
    });
    let server = MockLlmServer::start(vec![adi_json.to_string()]);
    configure_llm(&tmp, &server.base_url(), "mock-model", "mock-key");

    let out = forgeplan()
        .args(["reason", &adr, "--json"])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    assert!(out.status.success());
    let stdout = String::from_utf8_lossy(&out.stdout);
    // --json emits a progress line ("Analyzing X...") before the JSON
    // payload — extract the JSON block (first '{' to last '}').
    let json_start = stdout.find('{').expect("no JSON in output");
    let json_end = stdout.rfind('}').expect("no JSON in output");
    let json_str = &stdout[json_start..=json_end];
    let parsed: serde_json::Value =
        serde_json::from_str(json_str).expect("reason --json must emit valid JSON");
    assert!(
        parsed["adi_output"].is_object() || parsed["adi_analysis"].is_string(),
        "JSON output must carry the ADI fields; got:\n{stdout}"
    );
    server.stop();
}

