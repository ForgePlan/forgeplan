//! LLM-backed commands must call the configured OpenAI-compatible provider,
//! parse the response, and surface it — or fail with the `LLM not configured`
//! / `Fix:` contract when the provider is absent or errors.

use assert_cmd::Command;
use tempfile::TempDir;

#[path = "common/mock_llm.rs"]
mod mock_llm;
use mock_llm::{MockLlmServer, configure_llm};

fn forgeplan() -> Command {
    Command::cargo_bin("forgeplan").unwrap()
}

fn init_workspace(tmp: &TempDir) {
    forgeplan()
        .args(["init", "-y"])
        .current_dir(tmp.path())
        .assert()
        .success();
}

fn new_artifact(tmp: &TempDir, kind: &str, title: &str) -> String {
    let out = forgeplan()
        .args(["new", kind, title, "--allow-duplicate"])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "new {kind} failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    for line in stdout.lines() {
        if let Some(id) = line.trim().strip_prefix("ID:") {
            return id.trim().to_string();
        }
    }
    panic!("no ID parsed from new {kind}: {stdout}");
}

fn init_llm_workspace(tmp: &TempDir) -> MockLlmServer {
    init_workspace(tmp);
    let server = MockLlmServer::start(vec![]);
    configure_llm(tmp, &server.base_url(), "mock-model", "mock-key");
    server
}

// ── generate ────────────────────────────────────────────────────────────────

/// `forgeplan generate` must POST to the configured base URL, parse the
/// chat-completion response, and create a draft artifact whose body is the
/// LLM's reply. The mock proves the command actually called the provider.
#[test]
fn generate_creates_artifact_from_llm_response() {
    let tmp = TempDir::new().unwrap();
    init_workspace(&tmp);

    let llm_body = "## Problem\nGenerated by mock LLM.\n\n## Goals\n- test goal\n";
    let server = MockLlmServer::start(vec![llm_body.into()]);
    configure_llm(&tmp, &server.base_url(), "mock-model", "mock-key");

    // Debug: verify the config file has the llm block before spawning.
    let cfg_path = tmp.path().join(".forgeplan/config.yaml");
    eprintln!("config path: {}", cfg_path.display());
    let cfg = std::fs::read_to_string(&cfg_path).unwrap();
    eprintln!("config has llm: {}", cfg.contains("provider: openai"));
    eprintln!("config tail:\n{}", &cfg[cfg.len().saturating_sub(400)..]);
    eprintln!("MOCK_LLM_KEY: {:?}", std::env::var("MOCK_LLM_KEY"));
    assert!(
        cfg.contains("provider: openai"),
        "config.yaml must contain llm block; got:\n{}",
        &cfg[cfg.len().saturating_sub(500)..]
    );
    let out = forgeplan()
        .args(["generate", "prd", "A mock-generated PRD"])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "generate failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.contains("ID:"),
        "generate must print an artifact ID; got:\n{stdout}"
    );
    assert!(
        stdout.contains("AI-generated"),
        "generate must mark the source as AI-generated; got:\n{stdout}"
    );
    assert_eq!(server.requests(), 1, "exactly one LLM call expected");

    // The artifact must exist and contain the mock body.
    let list = forgeplan()
        .args(["list"])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    let list_out = String::from_utf8_lossy(&list.stdout);
    assert!(
        list_out.contains("mock-generated PRD") || list_out.contains("A mock-generated"),
        "generated artifact must appear in list; got:\n{list_out}"
    );
    server.stop();
}

